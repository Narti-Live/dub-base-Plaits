"""Rasterises the panel fonts (Inter) into an anti-aliased glyph atlas header."""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [  # name, file, pixel size
    ('F_LABEL', '/usr/share/fonts/opentype/inter/Inter-Bold.otf', 29),
    ('F_BIG', '/usr/share/fonts/opentype/inter/Inter-Bold.otf', 40),
    ('F_MED', '/usr/share/fonts/opentype/inter/Inter-SemiBold.otf', 23),
    ('F_SMALL', '/usr/share/fonts/opentype/inter/Inter-Medium.otf', 19),
    ('F_TINY', '/usr/share/fonts/opentype/inter/Inter-SemiBold.otf', 16),
]
out = open(sys.argv[1], 'w')
out.write('/* generated by tools/mkfonts.py (Inter, SIL OFL) */\n#include <stdint.h>\n')
out.write('typedef struct { int16_t w, h, ox, oy, adv; uint32_t off; } Glyph;\n')
out.write('typedef struct { int ascent, height; const Glyph *g; const uint8_t *px; } Font;\n')
names = []
for idx, (name, path, size) in enumerate(FONTS):
    f = ImageFont.truetype(path, size)
    asc, desc = f.getmetrics()
    glyphs, data = [], bytearray()
    for c in range(32, 127):
        ch = chr(c)
        l, t, r, b = f.getbbox(ch)
        adv = f.getlength(ch)
        w, h = max(0, r - l), max(0, b - t)
        if w and h:
            im = Image.new('L', (w, h), 0)
            ImageDraw.Draw(im).text((-l, -t), ch, font=f, fill=255)
            px = im.tobytes()
        else:
            px = b''
        glyphs.append((w, h, l, t, int(round(adv)), len(data)))
        data += px
    out.write('static const Glyph %s_g[95] = {\n' % name)
    out.write(',\n'.join('{%d,%d,%d,%d,%d,%d}' % g for g in glyphs))
    out.write('};\nstatic const uint8_t %s_px[%d] = {\n' % (name, len(data)))
    for i in range(0, len(data), 40):
        out.write(','.join(str(x) for x in data[i:i + 40]) + ',\n')
    out.write('};\n')
    names.append((name, asc, asc + desc))
out.write('static const Font g_fonts[%d] = {\n' % len(names))
out.write(',\n'.join('{%d,%d,%s_g,%s_px}' % (a, h, n, n) for n, a, h in names))
out.write('};\n')
for i, (n, _, _) in enumerate(names):
    out.write('#define %s (&g_fonts[%d])\n' % (n, i))
out.close()
